// CI browser coverage contracts. These checks do not launch or substitute for a browser.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const browser=fs.readFileSync(new URL('./responsive-browser.py',import.meta.url),'utf8');
test('browser native-color fixture is generated by the real inert PHP parser',()=>{
 const script=new URL('./native-defaults-browser-fixture.php',import.meta.url);
 const result=spawnSync(process.env.RACKLINE_PHP_BIN||'php',[script.pathname],{encoding:'utf8'});
 assert.equal(result.status,0,result.stderr||result.error?.message);assert.equal(result.stderr,'');
 const fixture=JSON.parse(result.stdout);assert.equal(fixture.display.color,'#2468ac');assert.equal(fixture.display.identityVerified,true);assert.equal(fixture.display.type,'Boot');assert.equal(fixture.expectedBackground,'rgb(36, 104, 172)');
 assert.match(browser,/native-defaults-browser-fixture\.php/);assert.match(browser,/display:nativeDisplay/);assert.match(browser,/geometry\['children'\]\[1\]\['bg'\]==native\['expectedBackground'\]/);assert.match(browser,/geometry\['children'\]\[1\]\['color'\]==native\['expectedForeground'\]/);
});
test('browser CI checks repeated banner recovery, computed Ember contrast and keyboard/mobile focus',()=>{
 assert.match(browser,/for _ in range\(3\)/);assert.match(browser,/getBoundingClientRect\(\)\.height'\)==0/);assert.match(browser,/status\.get_attribute\('role'\)=='status'/);
 assert.match(browser,/color_contrast\(appearance\['text'\],appearance\['fill'\]\)>=4\.5/);assert.match(browser,/color_contrast\(appearance\['border'\],appearance\['input'\]\)>=3/);
 assert.match(browser,/outlineColor'\)=='rgb\(108, 185, 255\)'/);assert.match(browser,/\('ember-status-'\+str\(w\),w,'ember'\) for w in \[390,1024,1440\]/);
});
